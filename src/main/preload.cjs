const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('vortex', {
  adminStatus: () => ipcRenderer.invoke('system:admin'),
  optimizerStatus: () => ipcRenderer.invoke('optimizer:status'),
  setAutomaticOptimizations: enabled => ipcRenderer.invoke('optimizer:set-automatic', enabled),
  liveMetrics: () => ipcRenderer.invoke('system:live'),
  updateStatus: () => ipcRenderer.invoke('updates:status'),
  checkUpdates: () => ipcRenderer.invoke('updates:check'),
  installUpdate: () => ipcRenderer.invoke('updates:install'),
  windowSettings: () => ipcRenderer.invoke('window:settings'),
  setWindowSettings: settings => ipcRenderer.invoke('window:settings-set', settings),
  minimizeToTray: () => ipcRenderer.invoke('window:minimize-tray'),
  startupStatus: () => ipcRenderer.invoke('system:startup'),
  setStartup: value => ipcRenderer.invoke('system:startup-set', value),
  telemetry: () => ipcRenderer.invoke('system:telemetry'),
  memoryProfiles: () => ipcRenderer.invoke('profiles:list'),
  saveMemoryProfile: name => ipcRenderer.invoke('profiles:save', name),
  deleteMemoryProfile: name => ipcRenderer.invoke('profiles:delete', name),
  applyMemoryProfile: name => ipcRenderer.invoke('profiles:apply', name),
  requestAdmin: () => ipcRenderer.invoke('system:request-admin'),
  overview: () => ipcRenderer.invoke('system:overview'),
  hardwareDetails: () => ipcRenderer.invoke('system:hardware'),
  services: () => ipcRenderer.invoke('system:services'),
  hvci: () => ipcRenderer.invoke('system:hvci'),
  history: () => ipcRenderer.invoke('system:history'),
  changeService: (name, mode, advanced = false) => ipcRenderer.invoke('system:change-service', name, mode, advanced),
  restoreService: id => ipcRenderer.invoke('system:restore-service', id),
  memorySnapshot: () => ipcRenderer.invoke('memory:snapshot'),
  cleanMemory: request => ipcRenderer.invoke('memory:clean', request),
  configureMemory: configuration => ipcRenderer.invoke('memory:auto', configuration),
  standbySnapshot: () => ipcRenderer.invoke('standby:snapshot'),
  purgeStandby: request => ipcRenderer.invoke('standby:purge', request),
  configureStandby: options => ipcRenderer.invoke('standby:schedule', options),
  gameProcesses: () => ipcRenderer.invoke('games:processes'),
  gameStatus: () => ipcRenderer.invoke('games:status'),
  gameCapabilities: () => ipcRenderer.invoke('games:capabilities'),
  gameRules: () => ipcRenderer.invoke('games:rules'),
  recommendGame: pid => ipcRenderer.invoke('games:recommend', pid),
  saveGameRule: (rule, previousMatch = null) => ipcRenderer.invoke('games:save-rule', rule, previousMatch),
  deleteGameRule: name => ipcRenderer.invoke('games:delete-rule', name),
  changeGameProcess: action => ipcRenderer.invoke('games:perform', action),
  inspectGameSettings: pid => ipcRenderer.invoke('games:inspect-settings', pid),
  activateGame: (pid, options) => ipcRenderer.invoke('games:activate', pid, options),
  stopGame: () => ipcRenderer.invoke('games:stop')
});
